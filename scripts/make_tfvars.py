#!/usr/bin/env python3
"""Generate terraform.tfvars for each Terraform folder at run time.

  python3 make_tfvars.py baseline   # terraform/00-baseline
  python3 make_tfvars.py stages     # 02-dns-records, 03-ipam, 04-privatelink

`stages` reads the baseline's `terraform output` and the grid info written by
seed_grid.py. Nothing secret is written: passwords and cloud credentials stay in
environment variables.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

from nios_wapi import load_state

REPO_ROOT = Path(__file__).resolve().parent.parent
TERRAFORM = REPO_ROOT / "terraform"
IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_-]*$")


def hcl(value, depth=0):
    """Render a Python value as HCL. Handles the types the tfvars here use."""
    pad = "  " * depth
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        # Stop Terraform treating ${ and %{ in a value as a template sequence.
        return json.dumps(value).replace("${", "$${").replace("%{", "%%{")
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(hcl(v, depth) for v in value) + "]"
    if isinstance(value, dict):
        lines = ["{"]
        names = {k: (k if IDENTIFIER.match(k) else json.dumps(k)) for k in value}
        width = max((len(n) for n in names.values()), default=0)
        for key in sorted(value):
            lines.append(f"{pad}  {names[key].ljust(width)} = {hcl(value[key], depth + 1)}")
        lines.append(f"{pad}}}")
        return "\n".join(lines)
    raise TypeError(f"cannot render {type(value).__name__} as HCL")


def write_tfvars(folder, values, header):
    path = TERRAFORM / folder / "terraform.tfvars"
    body = "\n".join(f"# {line}" for line in header) + "\n"
    width = max(len(key) for key in values)
    body += "\n".join(f"{key.ljust(width)} = {hcl(val)}" for key, val in values.items()) + "\n"
    path.write_text(body)
    print(f"  wrote {path.relative_to(REPO_ROOT)}")


def baseline_outputs():
    result = subprocess.run(
        ["terraform", f"-chdir={TERRAFORM / '00-baseline'}", "output", "-json"],
        capture_output=True, text=True, check=False)
    if result.returncode != 0 or not result.stdout.strip():
        sys.exit("ERROR: terraform output failed in 00-baseline. Has the baseline been applied?\n"
                 + result.stderr)
    return {k: v["value"] for k, v in json.loads(result.stdout).items()}


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in ("baseline", "stages"):
        print(__doc__)
        return 2
    header = ["Generated by scripts/make_tfvars.py at run time. Safe to edit; not committed."]

    if sys.argv[1] == "baseline":
        write_tfvars("00-baseline", {
            "name_prefix": os.getenv("LAB_NAME_PREFIX", "iac"),
            "aws_region": os.getenv("AWS_DEFAULT_REGION", "eu-central-1"),
            "azure_location": os.getenv("LAB_AZURE_LOCATION", "northeurope"),
            "relay_vm_size": os.getenv("LAB_RELAY_VM_SIZE", "Standard_D2s_v3"),
        }, header)
        return 0

    domain = os.getenv("LAB_DOMAIN", "examplecorp.test")
    out = baseline_outputs()
    grid = load_state("grid_info")
    if not grid.get("member_hostname"):
        sys.exit("ERROR: no grid info found. Run seed_grid.py before generating stage variables.")

    # Shown and edited on screen in challenge 2, so spell the settings out here.
    write_tfvars("02-dns-records", {
        "domain": domain,
        "app_ip": "10.30.0.50",
        "record_ttl": 300,
        "cname_aliases": ["shop"],
    }, header)
    write_tfvars("03-ipam", {"domain": domain}, header)
    write_tfvars("04-privatelink", {
        "domain": domain,
        "nios_member_hostname": grid["member_hostname"],
        "relay_ip": out["relay_public_ip"],
        "resource_group_name": out["azure_resource_group"],
        "location": out["azure_location"],
        "endpoints_subnet_id": out["endpoints_subnet_id"],
        "privatelink_zone_ids": out["privatelink_zone_ids"],
        "storage_account_ids": out["storage_account_ids"],
        "storage_account_names": out["storage_account_names"],
    }, header)
    return 0


if __name__ == "__main__":
    sys.exit(main())
